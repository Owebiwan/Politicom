def png(path, w, h, rows):
    raw = b"".join(b"\x00" + row for row in rows)

    def chunk(kind, body):
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))


def rgba(ch):
    c = PALETTE[ch]
    if c is None:
        return b"\x00\x00\x00\x00"
    return bytes(int(c[i:i + 2], 16) for i in (1, 3, 5)) + b"\xff"


def grid(name):
    rows = [r for r in S[name].strip("\n").split("\n")]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        sys.exit(f"{name}: sprite must be 16 x 16 ({len(rows)} rows, widths {[len(r) for r in rows]})")
    for r in rows:
        for ch in r:
            if ch not in PALETTE:
                sys.exit(f"{name}: unknown colour '{ch}'")
    return rows


def render(rows, scale):
    out = []
    for r in rows:
        line = b"".join(rgba(ch) * scale for ch in r)
        out.extend([line] * scale)
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    out = args[0] if args else os.path.join(os.path.dirname(__file__), "..", "..", "Game", "pixel")
    os.makedirs(out, exist_ok=True)
    for name in S:
        png(os.path.join(out, name + ".png"), 16 * SCALE, 16 * SCALE, render(grid(name), SCALE))
    if "--sheet" in sys.argv:
        sheet = sys.argv[sys.argv.index("--sheet") + 1]
        names = list(S)
        cols, cell = 10, 16 * 4 + 8
        rows_n = (len(names) + cols - 1) // cols
        canvas = [[b"\x22\x24\x2a\xff"] * (cols * cell) for _ in range(rows_n * cell)]
        for i, name in enumerate(names):
            px = render(grid(name), 4)
            ox, oy = (i % cols) * cell + 4, (i // cols) * cell + 4
            for y, line in enumerate(px):
                for x in range(16 * 4):
                    p = line[x * 4:x * 4 + 4]
                    if p[3]:
                        canvas[oy + y][ox + x] = p
        png(sheet, cols * cell, rows_n * cell, [b"".join(r) for r in canvas])
    print(f"{len(S)} sprites")


if __name__ == "__main__":
    main()
